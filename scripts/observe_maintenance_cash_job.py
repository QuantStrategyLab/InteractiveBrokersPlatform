def job_document(revision, job, entry):
    """Translate only reviewed service fields; keep every env/Secret reference."""
    spec = revision["spec"]
    if set(spec) - {"containers", "serviceAccountName", "timeoutSeconds", "containerConcurrency", "volumes"}:
        raise pilot.ReleaseError("job_spec_translation_unsupported")
    container = copy.deepcopy(spec["containers"][0])
    if set(container) - {"image", "name", "env", "resources", "workingDir", "volumeMounts",
            "command", "args", "ports", "startupProbe", "livenessProbe"}:
        raise pilot.ReleaseError("job_container_translation_unsupported")
    if (not container["image"].endswith("@" + IMAGE_DIGEST)
            or not spec.get("serviceAccountName") or not container.get("resources", {}).get("limits")
            or any(row["name"].startswith(("K_", "CLOUD_RUN_")) for row in container.get("env", []))):
        raise pilot.ReleaseError("job_runtime_unverified")
    for key in ("ports", "startupProbe", "livenessProbe"):
        container.pop(key, None)
    container.update(command=["/app/.venv/bin/python"], args=["-c", entry])
    annotations = revision.get("metadata", {}).get("annotations", {})
    network = {key: value for key, value in annotations.items() if key in NETWORK_KEYS}
    if not (network.get("run.googleapis.com/network-interfaces") or network.get("run.googleapis.com/vpc-access-connector")):
        raise pilot.ReleaseError("job_network_unverified")
    task = dict(serviceAccountName=spec["serviceAccountName"], containers=[container], maxRetries=0, timeoutSeconds="300")
    if "volumes" in spec:
        task["volumes"] = copy.deepcopy(spec["volumes"])
    return dict(apiVersion="run.googleapis.com/v1", kind="Job", metadata=dict(name=job,
        labels={"qsl-maintenance-cash": job}), spec=dict(template=dict(metadata=dict(annotations=network),
            spec=dict(taskCount=1, parallelism=1, template=dict(spec=task)))))


def verify_template(actual, wanted):
    """Check server readback, permitting only harmless API default fields."""
    try:
        spec, desired = actual["spec"], wanted["spec"]
        if spec.get("taskCount", 1) != 1 or spec.get("parallelism", 1) != 1:
            raise ValueError
        task, expected_task = copy.deepcopy(spec["template"]["spec"]), copy.deepcopy(desired["template"]["spec"])
        if task.get("maxRetries", 0) != 0 or str(task.get("timeoutSeconds")) != "300":
            raise ValueError
        for value in (task, expected_task):
            for row in value.get("containers", []):
                if row.get("resources", {}).get("limits", {}).get("cpu") == "1000m":
                    row["resources"]["limits"]["cpu"] = "1"
        task.setdefault("maxRetries", 0)
        task["timeoutSeconds"] = "300"
        # container names are generated by the API when absent in the source.
        for row, desired_row in zip(task["containers"], expected_task["containers"]):
            if "name" not in desired_row:
                row.pop("name", None)
        if task != expected_task:
            raise ValueError
    except (KeyError, TypeError, ValueError):
        raise pilot.ReleaseError("job_template_readback_unverified") from None


def verify_job(actual, document):
    job = document["metadata"]["name"]
    if (actual.get("metadata", {}).get("name") != job
            or actual.get("metadata", {}).get("labels", {}).get("qsl-maintenance-cash") != job):
        raise pilot.ReleaseError("job_ownership_unverified")
    annotations = actual.get("spec", {}).get("template", {}).get("metadata", {}).get("annotations", {})
    desired = document["spec"]["template"]["metadata"]["annotations"]
    for key in NETWORK_KEYS:
        left, right = annotations.get(key), desired.get(key)
        if key == "run.googleapis.com/network-interfaces" and left and right:
            left, right = pilot._json(left), pilot._json(right)
        if left != right:
            raise pilot.ReleaseError("job_network_readback_unverified")
    verify_template(actual["spec"]["template"], document["spec"]["template"])


def verify_execution(execution, job, document):
    name = execution.get("metadata", {}).get("name", "")
    if (not re.fullmatch(re.escape(job) + r"-[a-z0-9]+", name)
            or execution.get("metadata", {}).get("labels", {}).get("run.googleapis.com/job") != job):
        raise pilot.ReleaseError("execution_identity_unverified")
    verify_template(execution, document["spec"]["template"])
    return name


def report_namespace(revision, expected):
    rows = revision["spec"]["containers"][0].get("env", [])
    values = [row.get("value") for row in rows if row.get("name") == "EXECUTION_REPORT_GCS_URI"]
    if len(values) != 1 or not isinstance(values[0], str):
        raise pilot.ReleaseError("report_store_binding_unverified")
    base = values[0].rstrip("/")
    # The writer inserts its child before platform/profile/service segments;
    # the publisher's prefix can already include those segments.
    publisher._source_report_uri(expected["expected_report_prefix"].rstrip("/") + "/binding-check", base)
    return base + "/maintenance-cash"


def inspect_report(report, uri, expected, *, job, execution, started, now, namespace=None):
    """Job-only validation. Never forge a service revision for its publisher."""
    namespace = namespace or expected["expected_report_prefix"].rstrip("/") + "/maintenance-cash"
    publisher._source_report_uri(uri, namespace)
    # Check the original publisher scope without changing its physical revision
    # or publishing the Job report. Only the writer's isolation segment moves.
    original_uri = namespace.removesuffix("/maintenance-cash") + uri[len(namespace):]
    publisher._source_report_uri(original_uri, expected["expected_report_prefix"])
    diag, target = report.get("diagnostics", {}), report.get("runtime_target", {})
    if (report.get("schema_version") != "runtime_report.v1" or report.get("status") != "ok"
            or report.get("platform") != "interactive_brokers" or report.get("deploy_target") != "cloud_run"
            or any(report.get(key) != expected["expected_" + key] for key in ("project_id", "service_name", "account_scope"))
            or target.get("deployment_selector") != expected["expected_deployment_selector"]
            or tuple(target.get("account_selector", ())) != expected["expected_account_selector"]
            or diag.get("runtime_revision") or diag.get("maintenance_cash_observation") is not True
            or diag.get("execution_kind") != "cloud_run_job" or diag.get("cloud_run_job") != job
            or diag.get("cloud_run_execution") != execution
            or any(diag.get(key) != value for key, value in (("task_index", 0), ("task_attempt", 0), ("task_count", 1)))):
        raise pilot.ReleaseError("job_report_identity_unverified")
    facts = report.get("summary", {}).get("account_facts", {})
    if (facts.get("schema_version") != "ibkr_account_snapshot.v1" or facts.get("currency") != "USD"
            or tuple(facts.get("account_ids", ())) != expected["expected_account_selector"]):
        raise pilot.ReleaseError("job_report_account_unverified")
    begin, end, observed = [publisher._observed_timestamp(value) for value in (
        report.get("started_at"), report.get("finished_at"), facts.get("observed_at"))]
    if not started <= begin <= observed <= end <= now + timedelta(minutes=5) or begin < now - timedelta(minutes=10):
        raise pilot.ReleaseError("job_report_time_unverified")
    cash = publisher._project_cash(facts.get("cash"))
    from application.ibkr_cash_observations import inspect_cash_observations
    selected = [row for row in cash if row["currency"] == "USD"]
    fields = inspect_cash_observations(facts.get("broker_cash_observations"), observed_at=facts["observed_at"],
        selected_cash=selected[0] if len(selected) == 1 else None)
    if fields["status"] != "OBSERVED_FIELDS_ONLY":
        raise pilot.ReleaseError("job_native_cash_unverified")
    result = dict(status="OBSERVED_JOB_ONLY", source_identity_verified=True, saved_readback_verified=True,
        observed_at=observed.isoformat(), report_sha256=observer.digest(json.dumps(report, sort_keys=True)),
        cash_observations=fields, spendable_cash_verified=False, complete_obligations_verified=False)
    summary = report.get("summary", {}).get("broker_account_summary")
    if summary is not None:
        if (not isinstance(summary, dict) or summary.get("source_method") != "ibkr.reqAccountSummary"
                or tuple(summary.get("account_ids", ())) != expected["expected_account_selector"]
                or summary.get("query_completed") is not True or summary.get("snapshot_atomic") is not False):
            raise pilot.ReleaseError("account_summary_identity_unverified")
        first, last = [publisher._observed_timestamp(summary.get(key)) for key in (
            "observed_started_at", "observed_finished_at")]
        if not begin <= observed <= first <= last <= end:
            raise pilot.ReleaseError("account_summary_time_unverified")
        summary_fields = inspect_cash_observations(summary.get("broker_cash_observations"),
            observed_at=summary["observed_finished_at"])
        if summary_fields["status"] != "OBSERVED_FIELDS_ONLY":
            raise pilot.ReleaseError("account_summary_fields_unverified")
        result["account_summary_cash_observations"] = dict(source_method="ibkr.reqAccountSummary",
            observed_started_at=first.isoformat(), observed_finished_at=last.isoformat(), **summary_fields)
        diagnostic = summary.get("field_diagnostics")
        if diagnostic is not None:
            names = {"usd_rows", "usd_invalid_values", "usd_duplicate_rows", "base_rows", "other_currency_rows"}
            if (summary.get("request_scoped") is not True or not isinstance(diagnostic, dict)
                    or set(diagnostic) != {"SettledCash", "AvailableFunds", "FullAvailableFunds"}
                    or any(not isinstance(row, dict) or set(row) != names
                        or any(type(n) is not int or not 0 <= n <= 1000000 for n in row.values())
                        or row["usd_invalid_values"] > row["usd_rows"]
                        or row["usd_duplicate_rows"] != max(0, row["usd_rows"] - 1) for row in diagnostic.values())):
                raise pilot.ReleaseError("account_summary_diagnostic_unverified")
            result["account_summary_cash_observations"].update(request_scoped=True, field_diagnostics=diagnostic)
    funding = report.get("summary", {}).get("broker_funding_inputs")
    if funding is not None:
        if (not isinstance(funding, dict) or funding.get("schema_version") != "ibkr.funding_inputs.v1"
                or tuple(funding.get("account_ids", ())) != expected["expected_account_selector"]
                or funding.get("source_scope") != "TWS_SESSION_API_ORDERS_AND_CONTRACT_METADATA"
                or funding.get("snapshot_atomic") is not False or funding.get("open_orders_query_completed") is not True
                or any(funding.get(key) is not False for key in ("complete_cash_obligations_verified",
                    "account_fee_plan_verified", "account_trading_permissions_verified"))):
            raise pilot.ReleaseError("funding_inputs_identity_unverified")
        first, middle, last = [publisher._observed_timestamp(funding.get(key)) for key in (
            "observed_started_at", "orders_finished_at", "observed_finished_at")]
        previous = publisher._observed_timestamp(summary["observed_finished_at"]) if summary is not None else observed
        if not begin <= observed <= previous <= first <= middle <= last <= end:
            raise pilot.ReleaseError("funding_inputs_time_unverified")
        count, orders = funding.get("open_order_count"), funding.get("open_orders", [])
        if (type(count) is not int or not 0 <= count <= 1000000 or not isinstance(orders, list) or len(orders) != count
                or any(not isinstance(row, dict) or row.get("account") not in expected["expected_account_selector"] for row in orders)):
            raise pilot.ReleaseError("funding_orders_unverified")
        from application.ibkr_cash_observations import _decimal
        rules = funding.get("contract_rules")
        if (not isinstance(rules, dict) or rules.get("status") not in {"OBSERVED", "UNAVAILABLE"}
                or rules.get("symbol") != "TQQQ" or rules.get("currency") != "USD"):
            raise pilot.ReleaseError("funding_quantity_rules_unverified")
        if rules["status"] == "OBSERVED" and (type(rules.get("con_id")) is not int or rules["con_id"] <= 0
                or any(_decimal(rules.get(key)) is None or _decimal(rules[key]) <= 0 for key in ("minSize", "sizeIncrement"))):
            raise pilot.ReleaseError("funding_quantity_rules_unverified")
        step = _decimal(funding.get("configured_quantity_step"))
        mode = "UNKNOWN" if step is None or step <= 0 else "WHOLE_SHARES" if step >= 1 and step == step.to_integral_value() else "FRACTIONAL"
        result["funding_inputs"] = dict(status="OBSERVED_SOURCE_ONLY", source_scope=funding["source_scope"],
            observed_started_at=first.isoformat(), observed_finished_at=last.isoformat(), snapshot_atomic=False,
            observed_api_open_order_count=count, native_quantity_rules_status=rules["status"], configured_quantity_mode=mode,
            complete_cash_obligations_verified=False, account_fee_plan_verified=False, account_trading_permissions_verified=False)
    return result


def observe(expected, env, receipt, *, run=pilot.command, snapshot=pilot.snapshot,
            sleep=time.sleep, now=lambda: datetime.now(timezone.utc), load_report=publisher._load_gcs_report):
    if (env.get("GITHUB_REF") != "refs/heads/main" or env.get("GITHUB_RUN_ATTEMPT") != "1"
            or env.get("GITHUB_EVENT_NAME") != "workflow_dispatch" or env.get("GITHUB_REPOSITORY") != pilot.REPOSITORY
            or not re.fullmatch(r"[0-9]+", env.get("GITHUB_RUN_ID", ""))
            or env.get("MAINTENANCE_SOURCE_COMMIT") != SOURCE or env.get("MAINTENANCE_JOB") != "true"):
        raise pilot.ReleaseError("dispatch_not_admitted")
    ctx = SimpleNamespace(project=expected["expected_project_id"], region=env["CLOUD_RUN_REGION"], service=expected["expected_service_name"])
    common = ["--project=" + ctx.project, "--region=" + ctx.region]
    job = "ibkr-cash-read-" + env["GITHUB_RUN_ID"]
    def read(args, stage="job_read_failed"):
        return pilot._json(run(["gcloud", *args, "--format=json"], stage=stage))
    def jobs():
        return read(["run", "jobs", "list", *common])
    def executions():
        return read(["run", "jobs", "executions", "list", "--job=" + job, *common])
    before = snapshot(ctx, run)
    candidate = before["service"]["status"].get("latestCreatedRevisionName")
    if not pilot.NAME.fullmatch(candidate or ""):
        raise pilot.ReleaseError("candidate_not_admitted")
    revision = read(["run", "revisions", "describe", candidate, *common])
    observer.admit(expected, before, revision, SOURCE)
    document = job_document(revision, job, ENTRY.read_text())
    namespace = report_namespace(revision, expected)
    if any(row.get("metadata", {}).get("name") == job for row in jobs()):
        raise pilot.ReleaseError("job_name_occupied")
    result = dict(status="STOPPED", reason="job_not_completed", source_commit=SOURCE, image_digest=IMAGE_DIGEST,
        entry_sha256=observer.digest(ENTRY.read_text()), runtime_adopted=False, publisher_binding_changed=False,
        broker_write_requested=False, strategy_executed=False, job_create_attempted=False, job_execute_attempted=False,
        job_cleanup_verified=False, baseline_unchanged=False)
    def save():
        receipt.write_text(json.dumps(result, indent=2) + "\n")
        receipt.chmod(0o600)
    definition = receipt.with_name("maintenance-cash-job.private.json")
    created_uid = None
    save()
    try:
        definition.write_text(json.dumps(document))
        definition.chmod(0o600)
        result["job_create_attempted"] = True
        save()
        run(["gcloud", "run", "jobs", "replace", str(definition), *common, "--quiet", "--format=json"], stage="job_create_unknown", timeout=120)
        actual = read(["run", "jobs", "describe", job, *common])
        verify_job(actual, document)
        created_uid = actual.get("metadata", {}).get("uid")
        if not created_uid or executions():
            raise pilot.ReleaseError("job_preexecution_unverified")
        pilot.unchanged(before, snapshot(ctx, run))
        started = now()
        result["job_execute_attempted"] = True
        save()
        execution = read(["run", "jobs", "execute", job, *common, "--async", "--quiet"], "job_execute_unknown")
        name = verify_execution(execution, job, document)
        result["execution_sha256"] = observer.digest(name)
        save()
        for _ in range(90):
            execution = read(["run", "jobs", "executions", "describe", name, *common])
            verify_execution(execution, job, document)
            if execution.get("status", {}).get("completionTime"):
                break
            sleep(5)
        else:
            raise pilot.ReleaseError("job_completion_not_observed")
        status = execution["status"]
        result["execution_completed"] = True
        if status.get("succeededCount", 0) != 1 or status.get("failedCount", 0) or status.get("retriedCount", 0):
            raise pilot.ReleaseError("job_task_failed")
        for _ in range(12):
            logs = read(["logging", "read", f'resource.type="cloud_run_job" AND resource.labels.job_name="{job}" AND labels."run.googleapis.com/execution_name"="{name}" AND timestamp>="{started.isoformat()}" AND textPayload:"execution_report gs://"',
                "--project=" + ctx.project, "--limit=10"])
            uris = set()
            for row in logs:
                match = re.search(r"execution_report (gs://[^\s]+)", row.get("textPayload", ""))
                if match:
                    uris.add(publisher._source_report_uri(match[1], namespace))
            if len(uris) > 1:
                raise pilot.ReleaseError("job_report_ambiguous")
            if uris:
                uri = uris.pop()
                result.update(inspect_report(load_report(uri, project_id=ctx.project), uri, expected,
                    job=job, execution=name, started=started, now=now(), namespace=namespace))
                result.pop("reason", None)
                break
            sleep(5)
        else:
            raise pilot.ReleaseError("job_report_not_observed")
    except Exception as error:
        result.update(status="STOPPED", reason=str(error) if isinstance(error, pilot.ReleaseError) else "job_observation_failed")
    finally:
        definition.unlink(missing_ok=True)
        try:
            owned = [row for row in jobs() if row.get("metadata", {}).get("name") == job]
            if owned:
                if len(owned) != 1:
                    raise pilot.ReleaseError("cleanup_job_ownership_unverified")
                actual = read(["run", "jobs", "describe", job, *common])
                verify_job(actual, document)
                if created_uid and actual.get("metadata", {}).get("uid") != created_uid:
                    raise pilot.ReleaseError("cleanup_job_identity_changed")
                runs = executions()
                if len(runs) > 1:
                    raise pilot.ReleaseError("cleanup_execution_ambiguous")
                for execution in runs:
                    name = verify_execution(execution, job, document)
                    if not execution.get("status", {}).get("completionTime"):
                        run(["gcloud", "run", "jobs", "executions", "cancel", name, *common, "--quiet", "--format=json"], stage="job_cancel_unknown")
                        for _ in range(12):
                            execution = read(["run", "jobs", "executions", "describe", name, *common])
                            verify_execution(execution, job, document)
                            if execution.get("status", {}).get("completionTime"):
                                break
                            sleep(5)
                        else:
                            raise pilot.ReleaseError("cleanup_execution_still_active")
                run(["gcloud", "run", "jobs", "delete", job, *common, "--quiet", "--format=json"], stage="job_delete_unknown")
            if any(row.get("metadata", {}).get("name") == job for row in jobs()):
                raise pilot.ReleaseError("cleanup_job_remaining")
            result["job_cleanup_verified"] = True
        except Exception as error:
            result.update(status="STOPPED", cleanup_reason=str(error) if isinstance(error, pilot.ReleaseError) else "cleanup_unverified")
        try:
            pilot.unchanged(before, snapshot(ctx, run))
            result["baseline_unchanged"] = True
        except Exception:
            result.update(status="STOPPED", baseline_reason="baseline_unverified")
        save()
    return result


def main():
    receipt = Path(os.environ["RUNNER_TEMP"]) / "maintenance-cash.safe.json"
    result = dict(status="STOPPED", reason="preflight_failed", runtime_adopted=False)
    try:
        result = observe(identity.resolve_expected(), os.environ, receipt)
    except Exception as error:
        result["reason"] = str(error) if isinstance(error, pilot.ReleaseError) else "preflight_failed"
    receipt.write_text(json.dumps(result, indent=2) + "\n")
    receipt.chmod(0o600)
    print(json.dumps(result, sort_keys=True))
    return 0 if result["status"] == "OBSERVED_JOB_ONLY" and result.get("job_cleanup_verified") and result.get("baseline_unchanged") else 1


if __name__ == "__main__":
    raise SystemExit(main())
